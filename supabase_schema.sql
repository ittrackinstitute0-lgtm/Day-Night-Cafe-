-- 1. Create Menu Items Table
create table if not exists public.menu_items (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    name text not null,
    category text not null,          -- 'coffee', 'bakery', 'night_sips', 'bites', 'dessert'
    time_mood text default 'both',    -- 'day', 'night', 'both'
    price numeric not null,
    description text,
    image_url text,
    rating numeric default 4.9,
    is_featured boolean default false
);

-- 2. Create Reservations Table
create table if not exists public.reservations (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    customer_name text not null,
    phone text not null,
    email text,
    guests integer not null default 2,
    reservation_date date not null,
    reservation_time text not null,
    mood_preference text default 'both', -- 'day_sunshine' or 'night_lounge'
    special_request text
);

-- 3. Enable Row Level Security (RLS)
alter table public.menu_items enable row level security;
alter table public.reservations enable row level security;

-- 4. Policies for menu_items:
-- Anyone can read menu items
create policy "Allow public read on menu_items" 
on public.menu_items for select using (true);

-- Anyone can insert menu items (for demo / cafe admin interface)
create policy "Allow public insert on menu_items" 
on public.menu_items for insert with check (true);

-- Anyone can delete or update menu items
create policy "Allow public update on menu_items" 
on public.menu_items for update using (true);

create policy "Allow public delete on menu_items" 
on public.menu_items for delete using (true);

-- 5. Policies for reservations:
-- Anyone can submit a reservation
create policy "Allow public insert on reservations" 
on public.reservations for insert with check (true);

-- Allow reading reservations
create policy "Allow public read on reservations" 
on public.reservations for select using (true);

